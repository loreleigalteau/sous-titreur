"""Project storage on the local disk.

Each project is a folder named after its id, containing:
    project.json   the project (name, language, segments…)
    video.<ext>    the imported video, copied as-is

Projects live in the usual per-user application data folder, so they never
mix with the user's documents. It can be changed with the
SOUS_TITREUR_DATA_DIR environment variable.
"""

from __future__ import annotations

import os
import re
import shutil
import sys
import threading
import time
import uuid
from datetime import datetime, timezone
from pathlib import Path

from pydantic import TypeAdapter

from app.models import Project

PROJECT_FILE = "project.json"
# Project ids are generated by us (uuid4 hex); anything else is rejected,
# which also prevents paths such as "../../etc" from reaching the disk.
ID_PATTERN = re.compile(r"^[0-9a-f]{32}$")

_project_json = TypeAdapter(Project)


class ProjectNotFound(LookupError):
    pass


def replace_file(source: Path, target: Path, attempts: int = 10) -> None:
    """Replace `target` with `source` in one step.

    On Windows this fails while another program has the file open (an
    antivirus or the search indexer often does, briefly): try again a few
    times before giving up.
    """
    for attempt in range(attempts):
        try:
            os.replace(source, target)
            return
        except PermissionError:
            if attempt == attempts - 1:
                raise
            time.sleep(0.05 * (attempt + 1))


def default_data_dir() -> Path:
    override = os.environ.get("SOUS_TITREUR_DATA_DIR")
    if override:
        return Path(override).expanduser()
    home = Path.home()
    if sys.platform == "darwin":
        return home / "Library" / "Application Support" / "sous-titreur"
    if os.name == "nt":
        return Path(os.environ.get("APPDATA", home / "AppData" / "Roaming")) / "sous-titreur"
    return Path(os.environ.get("XDG_DATA_HOME", home / ".local" / "share")) / "sous-titreur"


def safe_suffix(filename: str) -> str:
    """Keep only a plain file extension (e.g. ".mp4"), or nothing."""
    suffix = Path(filename).suffix.lower()
    return suffix if re.fullmatch(r"\.[a-z0-9]{1,10}", suffix) else ""


class ProjectStore:
    def __init__(self, root: Path) -> None:
        self.root = root
        self.root.mkdir(parents=True, exist_ok=True)
        # The transcription thread and the API both save projects.
        self._lock = threading.Lock()

    def _folder(self, project_id: str) -> Path:
        if not ID_PATTERN.match(project_id):
            raise ProjectNotFound(project_id)
        return self.root / project_id

    def create(self, name: str, video_suffix: str) -> Project:
        project = Project(
            id=uuid.uuid4().hex,
            name=name,
            video_filename=f"video{video_suffix}",
            created_at=datetime.now(timezone.utc).isoformat(timespec="seconds"),
        )
        self._folder(project.id).mkdir()
        self.save(project)
        return project

    def get(self, project_id: str) -> Project:
        path = self._folder(project_id) / PROJECT_FILE
        # Read under the same lock as saves: on Windows, a file being read
        # cannot be replaced, so a save happening at that moment would fail.
        with self._lock:
            if not path.is_file():
                raise ProjectNotFound(project_id)
            data = path.read_bytes()
        return _project_json.validate_json(data)

    def save(self, project: Project) -> None:
        folder = self._folder(project.id)
        # Write to a temporary file then rename it: the rename is atomic, so a
        # crash in the middle of a save can never leave a half-written project.
        tmp = folder / f"{PROJECT_FILE}.tmp"
        with self._lock:
            tmp.write_bytes(_project_json.dump_json(project, indent=2))
            replace_file(tmp, folder / PROJECT_FILE)

    def list(self) -> list[Project]:
        projects = []
        for folder in self.root.iterdir():
            try:
                projects.append(self.get(folder.name))
            except (ProjectNotFound, ValueError):
                continue  # not a project, or unreadable: ignore it
        return sorted(projects, key=lambda p: p.created_at, reverse=True)

    def delete(self, project_id: str) -> None:
        folder = self._folder(project_id)
        if not folder.is_dir():
            raise ProjectNotFound(project_id)
        shutil.rmtree(folder)

    def video_path(self, project: Project) -> Path:
        return self._folder(project.id) / project.video_filename

    def frames_dir(self, project_id: str) -> Path:
        """Folder of the subtitle images uploaded for a video export."""
        return self._folder(project_id) / "frames"

    def waveform_path(self, project_id: str) -> Path:
        """Cache of the sound wave shown in the timeline."""
        return self._folder(project_id) / "waveform.json"

    def export_path(self, project_id: str) -> Path:
        """The last exported video with burned-in subtitles."""
        return self._folder(project_id) / "export.mp4"
